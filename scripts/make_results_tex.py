#!/usr/bin/env python
"""results.tex: LaTeX tables of the frozen-100 final benchmark (booktabs).

    python scripts/make_results_tex.py --run outputs/final_jit --run outputs/final_pmf --run outputs/final_sit --run outputs/final_imf --out results.tex

Tables: (1) one per model in the manuscript's Table-1 layout: rows = Degraded + 6 methods, column groups = 5 problems
with LPIPS / PSNR / SSIM, best per column in bold (SDEdit and Degraded excluded from the bold);
(2) a cross-model LPIPS summary; (3) the per-cell hyperparameters actually used.
"""
import argparse, csv
from pathlib import Path

PROBLEMS = ["denoising", "deblur", "super_resolution", "random_inpaint", "box_inpaint"]
PT = {"denoising": "Denoising", "deblur": "Deblurring", "super_resolution": "2$\\times$ SR", "random_inpaint": "Random inpaint.", "box_inpaint": "Box inpaint."}
METHODS = ["sdedit", "pnp", "dflow", "mpc_rhc", "mpc_delta_t", "rhso"]
MT = {"sdedit": "SDEdit", "pnp": "PnP-Flow", "dflow": "D-Flow", "mpc_rhc": "MPC-RHC", "mpc_delta_t": "MPC-$\\Delta t$", "rhso": "RHSO (ours)"}
MODELS = [("pmf", "pMF-L/16 (pixel, MeanFlow)"), ("jit", "JiT-B/16 (pixel, standard flow)"), ("imf", "iMF-B-2 (latent, MeanFlow)"), ("sit", "SiT-XL/2 (latent, standard flow)")]
HP = {"sdedit": ["steps"], "pnp": ["num_pnp_steps", "gamma0", "alpha"], "dflow": ["num_opt_steps", "lr"],
      "mpc_rhc": ["K", "lam", "lr"], "mpc_delta_t": ["num_mpc_steps", "n_ctrl", "lam", "lr"], "rhso": ["num_rhso_steps", "num_opt_steps", "lr", "mu"]}
HN = {"steps": "steps", "num_pnp_steps": "N", "gamma0": "\\gamma_0", "alpha": "\\alpha", "num_opt_steps": "M", "lr": "\\mathrm{lr}",
      "K": "K", "lam": "\\lambda", "num_mpc_steps": "N", "n_ctrl": "n_\\mathrm{ctrl}", "num_rhso_steps": "N", "mu": "\\mu"}


def g(v):
    x = float(v); return ("%g" % x) if abs(x) < 1e4 else ("%.0f" % x)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run", action="append", required=True); p.add_argument("--out", default="results.tex")
    a = p.parse_args()
    R = {}
    for run in a.run:
        for r in csv.DictReader(open(Path(run) / "results.csv")):
            if r.get("status", "ok") == "ok": R[(r["model"], r["problem"], r["method"])] = r
    L = ["% Generated by scripts/make_results_tex.py from " + ", ".join(a.run),
         "% Frozen ImageNet-100 (class seed 42 / image seed 43), t0 = 1.0, beta = 1, seed 42, 100 images per cell;",
         "% every cell uses its Stage-2 winner restricted to the Stage-1 grid (docs/best_hyperparameters_t1.md).",
         "% Requires \\usepackage{booktabs}.", ""]
    # ---- per-model tables
    for m, title in MODELS:
        if not any(k[0] == m for k in R): continue
        L += ["\\begin{table*}[t]", "\\centering", "\\small", "\\setlength{\\tabcolsep}{3.5pt}",
              "\\caption{%s on the frozen ImageNet-100 at $t_0 = 1$: LPIPS$\\downarrow$ / PSNR$\\uparrow$ / SSIM$\\uparrow$ over 100 images. Best guided method per column in bold.}" % title,
              "\\label{tab:final_%s}" % m,
              "\\begin{tabular}{l" + "ccc" * len(PROBLEMS) + "}", "\\toprule",
              " & " + " & ".join("\\multicolumn{3}{c}{%s}" % PT[pr] for pr in PROBLEMS) + " \\\\",
              " ".join("\\cmidrule(lr){%d-%d}" % (2 + 3 * i, 4 + 3 * i) for i in range(len(PROBLEMS))),
              "Method & " + " & ".join("LPIPS & PSNR & SSIM" for _ in PROBLEMS) + " \\\\", "\\midrule"]
        best = {}
        for pr in PROBLEMS:
            rows = [R[(m, pr, me)] for me in METHODS[1:] if (m, pr, me) in R]
            best[(pr, "lpips")] = min(float(r["lpips"]) for r in rows); best[(pr, "psnr")] = max(float(r["psnr"]) for r in rows); best[(pr, "ssim")] = max(float(r["ssim"]) for r in rows)
        d = [R[(m, pr, "rhso")] for pr in PROBLEMS]
        L.append("Degraded & " + " & ".join("%.3f & %.2f & %.3f" % (float(r["degraded_lpips"]), float(r["degraded_psnr"]), float(r["degraded_ssim"])) for r in d) + " \\\\")
        L.append("\\midrule")
        for me in METHODS:
            cells = []
            for pr in PROBLEMS:
                r = R.get((m, pr, me))
                if r is None: cells.append("-- & -- & --"); continue
                v = [("lpips", float(r["lpips"]), "%.3f"), ("psnr", float(r["psnr"]), "%.2f"), ("ssim", float(r["ssim"]), "%.3f")]
                cells.append(" & ".join(("\\textbf{%s}" % (f % x)) if (me != "sdedit" and abs(x - best[(pr, k)]) < 1e-9) else (f % x) for k, x, f in v))
            L.append("%s & %s \\\\" % (MT[me], " & ".join(cells)))
        L += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    # ---- cross-model LPIPS summary
    L += ["\\begin{table}[t]", "\\centering", "\\small", "\\setlength{\\tabcolsep}{4pt}",
          "\\caption{LPIPS$\\downarrow$ of every method on the frozen ImageNet-100 at $t_0 = 1$, all four priors. Best guided method per row in bold.}",
          "\\label{tab:final_lpips_summary}", "\\begin{tabular}{ll" + "c" * len(METHODS) + "}", "\\toprule",
          "Prior & Problem & " + " & ".join(MT[me] for me in METHODS) + " \\\\", "\\midrule"]
    for m, title in MODELS:
        if not any(k[0] == m for k in R): continue
        for i, pr in enumerate(PROBLEMS):
            vals = [float(R[(m, pr, me)]["lpips"]) if (m, pr, me) in R else None for me in METHODS]
            b = min(v for v in vals[1:] if v is not None)
            cells = ["--" if v is None else ("\\textbf{%.3f}" % v if (j > 0 and abs(v - b) < 1e-9) else "%.3f" % v) for j, v in enumerate(vals)]
            L.append("%s & %s & %s \\\\" % (title.split(" (")[0] if i == 0 else "", PT[pr], " & ".join(cells)))
        L.append("\\midrule")
    L[-1] = "\\bottomrule"; L += ["\\end{tabular}", "\\end{table}", ""]
    # ---- hyperparameters
    L += ["\\begin{table*}[t]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
          "\\caption{Hyperparameters used in every cell of the final benchmark (the lowest-LPIPS Stage-2 configuration inside the pre-registered grid, 8 tuning images).}",
          "\\label{tab:final_hparams}", "\\begin{tabular}{ll" + "l" * len(PROBLEMS) + "}", "\\toprule",
          "Prior & Method & " + " & ".join(PT[pr] for pr in PROBLEMS) + " \\\\", "\\midrule"]
    for m, title in MODELS:
        if not any(k[0] == m for k in R): continue
        for i, me in enumerate(METHODS):
            cells = []
            for pr in PROBLEMS:
                r = R.get((m, pr, me))
                cells.append("--" if r is None else "$" + ",\\ ".join("%s{=}%s" % (HN[k], g(r[k])) for k in HP[me] if r.get(k) not in (None, "")) + "$")
            L.append("%s & %s & %s \\\\" % (title.split(" (")[0] if i == 0 else "", MT[me], " & ".join(cells)))
        L.append("\\midrule")
    L[-1] = "\\bottomrule"; L += ["\\end{tabular}", "\\end{table*}", ""]
    Path(a.out).write_text("\n".join(L) + "\n"); print("wrote", a.out, "(%d lines)" % len(L))


if __name__ == "__main__":
    main()
